  <h1 id="about-title">О проекте</h1>
  <p>
    «Простой русский» оценивает, насколько легко читать текст на русском языке: сколько лет обучения
    нужно, чтобы его понять, и что именно мешает пониманию. Сервис помогает писать понятнее
    тексты для сайтов, документов, инструкций и писем.
  </p>

  <h2>Приватность</h2>
  <p>
    Текст обрабатывается на вашем устройстве: оценку считает программа, работающая прямо в
    браузере или в настольном приложении. Наружу текст уходит, только если вы сами подключите
    оценку с помощью языковой модели, и только выбранному провайдеру. На сайте нет счётчиков и
    сторонних скриптов.
  </p>

  <h2>Как считается оценка</h2>
  <p>
    Пять формул читаемости, адаптированных для русского языка: Flesch-Kincaid, Coleman-Liau, SMOG,
    ARI и упрощённая Dale-Chale. Каждая даёт число лет обучения, нужное для понимания текста.
    Главная оценка — их среднее.
  </p>
  <p>
    Предложения делятся по правилам библиотеки razdel: сокращения вроде «т. е.», «ст.» и инициалы
    не обрывают предложение. Слово — буквы, внутри допустимы дефис и апостроф; числа словами не
    считаются. Слог — гласная буква; аббревиатура без гласных («ВВП») читается по буквам. Сложное
    слово — больше четырёх слогов.
  </p>
  <p>
    Коэффициенты формул подобраны на текстах с экспертной оценкой уровня — от детских сказок до
    законов. Текстов немного, поэтому оценка ориентировочная: в среднем она отличается от
    экспертной на год с небольшим.
  </p>

  <h2>Оценка с помощью LLM</h2>
  <p>
    Языковая модель читает текст целиком, ставит оценку по той же шкале и перечисляет главные
    препятствия для понимания с цитатами и вариантами попроще. Подключается в
    <a href="#settings">настройках</a>: свой ключ API у Anthropic, OpenAI или OpenRouter либо модель,
    запущенная на этом компьютере в Ollama или LM Studio.
  </p>

